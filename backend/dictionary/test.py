"""
Integration test for backend.dictionary.

This file does NOT build or modify the dictionary resource.

Flow:
    TranslationRequest (backend.schema)
        ->
    DashboardExtractor (backend.dictionary.processor)
        ->
    DashboardEntry
        ->
    TranslationResponse (backend.schema)

Run from project root:

    python -m backend.dictionary.test
"""

from __future__ import annotations

from backend.schema import (
    TranslationMode,
    TranslationRequest,
    TranslationResponse,
)
from backend.dictionary.processor import DashboardExtractor


def main() -> None:
    # ------------------------------------------------------------
    # 1. Create an actual request using the application's schema.
    #
    # "sophisticated" is the example dictionary request already
    # documented in backend/schema.py. No dictionary entry is
    # created or injected by this test.
    # ------------------------------------------------------------
    request = TranslationRequest(
        text="sophisticated",
        mode=TranslationMode.DICTIONARY,
    )

    # ------------------------------------------------------------
    # 2. Use the real dictionary processor.
    #
    # create_json.py is NOT called here.
    # The processor only loads the resource that has already been
    # generated by create_json.py.
    # ------------------------------------------------------------
    extractor = DashboardExtractor()

    entries = extractor.extract((request.text,))

    if not entries:
        raise RuntimeError(
            f"No dictionary entry found for: {request.text!r}. "
            "The test does not create or inject a fake dictionary entry."
        )

    # ------------------------------------------------------------
    # 3. Convert real DashboardEntry results into the application's
    #    TranslationResponse schema.
    #
    # TranslationResponse currently defines translation as one string,
    # so multiple dictionary entries/meanings are represented as text.
    # ------------------------------------------------------------
    translation_parts: list[str] = []

    for entry in entries:
        if entry.meanings:
            meanings = "; ".join(entry.meanings)
            translation_parts.append(
                f"{entry.term}: {meanings}"
            )
        else:
            translation_parts.append(entry.term)

    translation = "\n".join(translation_parts).strip()

    response = TranslationResponse(
        text=request.text,
        translation=translation,
        mode=request.mode,
    )

    # ------------------------------------------------------------
    # 4. Print the actual schema objects.
    # ------------------------------------------------------------
    print("=" * 60)
    print("REQUEST")
    print("=" * 60)
    print(request.model_dump_json(indent=2))

    print()
    print("=" * 60)
    print("DICTIONARY ENTRIES")
    print("=" * 60)

    for entry in entries:
        print(f"term       : {entry.term}")
        print(f"type       : {entry.entry_type}")
        print(f"IPA        : {entry.ipas}")
        print(f"meanings   : {entry.meanings}")
        print("-" * 60)

    print()
    print("=" * 60)
    print("RESPONSE")
    print("=" * 60)
    print(response.model_dump_json(indent=2))


if __name__ == "__main__":
    main()
